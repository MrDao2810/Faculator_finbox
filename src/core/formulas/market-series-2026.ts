/** Một phiên: ngày ISO, mở, cao, thấp, đóng, khối lượng khớp lệnh. */
type Phien = readonly [
  date: string,
  open: number,
  high: number,
  low: number,
  close: number,
  volume: number,
];

function nen(rows: ReadonlyArray<Phien>): ReadonlyArray<SeriesRow> {
  return rows.map(([date, open, high, low, close, volume]) => ({
    date,
    open,
    high,
    low,
    close,
    volume,
  }));
}

function dongCua(rows: ReadonlyArray<Phien>): ReadonlyArray<number> {
  return rows.map((row) => row[4]);
}

